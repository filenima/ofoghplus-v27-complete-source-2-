export interface GeoPricingTier {
  /** شناسهٔ پلن (همان PlanId در lib/plans-static) */
  id: string;
  /** نام نمایشی فارسی */
  name: string;
  /** قیمت پایهٔ سالانه به تومان (پیش از پله‌های افزایش قیمت) */
  basePriceToman: number;
  /** دورهٔ صورتحساب */
  period: string;
  /** خلاصهٔ یک‌خطی سقف‌ها و امکانات کلیدی */
  summary: string;
  /** آیا در صفحه قیمت نمایش داده می‌شود؟ */
  visible: boolean;
}

export interface GeoFaq {
  question: string;
  answer: string;
}

export interface GeoKeyPage {
  /** مسیر نسبی (بدون دامنه) */
  path: string;
  /** توضیح یک‌خطی فارسی برای موتورهای مولد */
  description: string;
}

export interface GeoFacts {
  brand: {
    /** نام فارسی پیش‌فرض برند (منبع: تنظیمات برندینگ) */
    fa: string;
    /** نام لاتین برای entity دوزبانه */
    en: string;
    /** دامنهٔ اصلی */
    domain: string;
    /** سال تأسیس شمسی — تا پیش از اعلام رسمی مالک، منتشر نشده (دقت > کامل بودن) */
    foundedYearShamsi: string | null;
    /** دسته‌بندی محصول */
    category: string;
    /** مدل ارائه */
    deliveryModel: string;
    /** کشور و دفتر مرکزی */
    hq: string;
    /** پشتیبانی فارسی */
    support: string;
  };
  /** ۱۶ ماژول — عنوان + توضیح یک‌خطی (منبع: lib/landing-config.ts و /features) */
  modules: { label: string; description: string }[];
  /** ماژول تخصصی طلافروشی — تمایز اصلی برند (منبع: lib/industry-data.ts و /industries/gold-shop) */
  goldModule: {
    title: string;
    goldPriceApi: string;
    invoiceTax: string;
    weightInventory: string;
    buyback: string;
    moadian: string;
  };
  /** پلن‌ها — قیمت پایهٔ سالانه (منبع: lib/plans-static.ts؛ قیمت زنده همیشه از getEffectivePlans) */
  pricing: {
    currency: string;
    tiers: GeoPricingTier[];
    freeTrial: string;
    freeForeverPlan: string;
    paymentMethods: string;
    priceStepsNote: string;
  };
  /** صنایع پشتیبانی‌شده (منبع: lib/industry-data.ts — ۱۱ صنعت) */
  industries: string[];
  /** وضعیت اتصال به سامانه مودیان (منبع: /moadian-invoice و /features) */
  moadian: string;
  /** قابلیت آفلاین (منبع: lib/landing-config.ts — اپ موبایل و PWA) */
  offline: string;
  /** فروشگاه آنلاین‌ساز (منبع: /shop/[slug] و اتصال ووکامرس/دیجی‌کالا/باسلام) */
  shopBuilder: string;
  /** اتصال بانکی — سه لایه، بدون دریافت رمز بانکی (منبع: lib/hub-content/banks.ts) */
  bankIntegration: string;
  /** هوش مصنوعی بومی (منبع: lib/landing-config.ts) */
  ai: string;
  /** امنیت (منبع: lib/landing-config.ts — امنیت سطح بانکی) */
  security: string;
  /** مهاجرت از نرم‌افزارهای دیگر (منبع: صفحه قیمت و llms.txt) */
  migration: string;
  /** کاربران هدف */
  targetUsers: string;
  /** تمایزهای کلیدی نسبت به رقبا */
  differentiators: string[];
  /** صفحات کلیدی قابل‌ارجاع برای AI */
  keyPages: GeoKeyPage[];
}

