/**
 * جایگزینی توکن‌های برند/قیمت در متن FACTS.
 * @param priceList فهرست قیمت زنده (مثلاً «پایه ۹٬۷۵۰٬۰۰۰ تومان، ...») — برای توکن {priceList}
 */
export function factsBrand(text: string, brand: string, priceList?: string): string {
  let out = text.replaceAll("{brand}", brand);
  if (priceList !== undefined) out = out.replaceAll("{priceList}", priceList);
  return out;
}

/** رندر FAQ به خط‌های «- **پرسش** — پاسخ» برای llms.txt / llms-full.txt */
export function renderFaqLines(
  faqs: readonly GeoFaq[],
  brand: string,
  priceList?: string
): string[] {
  return faqs.map(
    (f) => `- **${factsBrand(f.question, brand, priceList)}** — ${factsBrand(f.answer, brand, priceList)}`
  );
}

