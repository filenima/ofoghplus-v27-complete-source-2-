/** ریال → نمایش ارزی (نرخ‌ها به تومان از سرور می‌آیند) */
export function rialToCurrencyLabel(rial: string | number | bigint, code: StorefrontCurrencyCode, usdRateToman?: number | null, cnyRateToman?: number | null): string {
  const n = typeof rial === "bigint" ? Number(rial) : Number(rial);
  const toman = Math.trunc(n / 10);
  if (code === "IRT") return `${new Intl.NumberFormat("fa-IR").format(toman)} تومان`;
  const rate = code === "USD" ? usdRateToman : cnyRateToman;
  if (!rate || rate <= 0) return `${new Intl.NumberFormat("fa-IR").format(toman)} تومان`;
  const converted = toman / rate;
  const symbol = code === "USD" ? "$" : "¥";
  return `${symbol}${new Intl.NumberFormat("en-US", { maximumFractionDigits: 0 }).format(Math.round(converted))}`;
}
