/** merge ایمن: مقادیر ذخیره‌شده مالک روی پیش‌فرض‌ها (برای نسخه‌های آینده) */
export function mergeStorefrontContent(
  base: StorefrontContent,
  override: Partial<StorefrontContent> | null | undefined
): StorefrontContent {
  if (!override) return base;
  return {
    banner: { ...base.banner, ...(override.banner ?? {}) },
    announcement: override.announcement ?? base.announcement,
    features: override.features?.length ? override.features : base.features,
    stats: override.stats?.length ? override.stats : base.stats,
    about: { ...base.about, ...(override.about ?? {}) },
    header: { ...base.header, ...(override.header ?? {}) },
    footer: { ...base.footer, ...(override.footer ?? {}) },
    trustNotes: override.trustNotes?.length ? override.trustNotes : base.trustNotes,
    sections: { ...base.sections, ...(override.sections ?? {}) },
  };
}

/** اعتبارسنجی محتوای ویرایش‌شدهٔ مالک — سقف طول و نوع */

/**
 * Task 3-a — تصویر اسلاید کاروسل معتبر: بنر آمادهٔ پلتفرم، آپلود مالک
 * (storefront یا مدیریت فایل) یا URL کامل https؛ خروجی نامعتبر = رد اسلاید.
 */
function sanitizeBannerSlideImage(raw: unknown): string {
  if (typeof raw !== "string") return "";
  const s = raw.trim();
  if (!s || s.length > 600) return "";
  return s.startsWith("/banners/") || s.startsWith("/uploads/") || s.startsWith("https://") ? s : "";
}

export function sanitizeStorefrontContent(raw: unknown): Partial<StorefrontContent> | null {
  if (!raw || typeof raw !== "object") return null;
  const c = raw as Record<string, unknown>;
  const str = (v: unknown, max: number): string | undefined => {
    if (typeof v !== "string") return undefined;
    const s = v.trim();
    return s ? s.slice(0, max) : undefined;
  };
  const out: Partial<StorefrontContent> = {};
  if (c.banner && typeof c.banner === "object") {
    const b = c.banner as Record<string, unknown>;
    // تصویر بنر معتبر: بنرهای آمادهٔ پلتفرم، آپلود مالک یا URL کامل https
    const img =
      typeof b.image === "string" &&
      (b.image.startsWith("/banners/") || b.image.startsWith("/uploads/storefront/") || b.image.startsWith("https://"))
        ? b.image.trim().slice(0, 600)
        : null;
    // Task 3-a — اسلایدهای کاروسل: هر اسلاید یک تصویر معتبر + متن‌های اختیاری
    const slides: BannerSlide[] = Array.isArray(b.slides)
      ? b.slides
          .filter((s): s is Record<string, unknown> => !!s && typeof s === "object")
          .slice(0, 8) // سقف ۸ اسلاید
          .map((s) => ({
            image: sanitizeBannerSlideImage(s.image),
            title: str(s.title, 120),
            subtitle: str(s.subtitle, 400),
            ctaLabel: str(s.ctaLabel, 40),
            ctaLink: str(s.ctaLink, 500),
            badge: str(s.badge, 60),
          }))
          .filter((s) => s.image)
          .map((s) => {
            // فیلدهای اختیاری خالی را حذف می‌کنیم تا JSON ذخیره‌شده کوچک بماند
            const out: BannerSlide = { image: s.image };
            if (s.title) out.title = s.title;
            if (s.subtitle) out.subtitle = s.subtitle;
            if (s.ctaLabel) out.ctaLabel = s.ctaLabel;
            if (s.ctaLink) out.ctaLink = s.ctaLink;
            if (s.badge) out.badge = s.badge;
            return out;
          })
      : [];
    out.banner = {
      mode: b.mode === "image" ? "image" : "cinematic",
      badge: str(b.badge, 60) ?? "",
      title: str(b.title, 120) ?? "",
      subtitle: str(b.subtitle, 400) ?? "",
      ctaLabel: str(b.ctaLabel, 40) ?? "",
      ctaLink: str(b.ctaLink, 500) ?? "#products",
      image: img,
      // آرایهٔ خالی هم ذخیره می‌شود تا «حذف همهٔ اسلایدها» بعد از ذخیره ماندگار باشد
      ...(slides.length > 0 ? { slides } : { slides: [] }),
    };
  }
  if (typeof c.announcement === "string") out.announcement = c.announcement.slice(0, 200);
  if (Array.isArray(c.features)) {
    out.features = c.features
      .filter((f): f is Record<string, unknown> => !!f && typeof f === "object")
      .slice(0, 6)
      .map((f) => ({
        icon: ["truck", "shield", "support", "price"].includes(String(f.icon)) ? String(f.icon) : "truck",
        title: str(f.title, 60) ?? "",
        text: str(f.text, 200) ?? "",
      }))
      .filter((f) => f.title);
  }
  if (Array.isArray(c.stats)) {
    out.stats = c.stats
      .filter((s): s is Record<string, unknown> => !!s && typeof s === "object")
      .slice(0, 4)
      .map((s) => ({ label: str(s.label, 60) ?? "", value: str(s.value, 30) ?? "" }))
      .filter((s) => s.label);
  }
  if (c.about && typeof c.about === "object") {
    const a = c.about as Record<string, unknown>;
    out.about = { title: str(a.title, 100) ?? "", text: str(a.text, 2000) ?? "" };
  }
  if (c.header && typeof c.header === "object") {
    const h = c.header as Record<string, unknown>;
    // لوگو/رنگ معتبر: آپلود پلتفرم، بنر آماده یا https کامل
    const isSafeMedia = (v: unknown): v is string =>
      typeof v === "string" &&
      (v.startsWith("/uploads/storefront/") || v.startsWith("/banners/") || v.startsWith("https://"));
    const logo = isSafeMedia(h.logoUrl) ? h.logoUrl.trim().slice(0, 600) : null;
    const accent =
      typeof h.accentColor === "string" && /^#?[0-9a-fA-F]{6}$/.test(h.accentColor.trim())
        ? (h.accentColor.trim().startsWith("#") ? h.accentColor.trim() : `#${h.accentColor.trim()}`)
        : null;
    out.header = {
      tagline: str(h.tagline, 60) ?? "",
      links: Array.isArray(h.links)
        ? h.links
            .filter((l): l is Record<string, unknown> => !!l && typeof l === "object")
            .slice(0, 8)
            .map((l) => ({ label: str(l.label, 40) ?? "", href: str(l.href, 500) ?? "#" }))
            .filter((l) => l.label)
        : [],
      logoUrl: logo,
      accentColor: accent,
      showSearch: typeof h.showSearch === "boolean" ? h.showSearch : true,
    };
  }
  if (c.footer && typeof c.footer === "object") {
    const f = c.footer as Record<string, unknown>;
    const columns = Array.isArray(f.columns)
      ? f.columns
          .filter((col): col is Record<string, unknown> => !!col && typeof col === "object")
          .slice(0, 3)
          .map((col) => ({
            title: str(col.title, 60) ?? "",
            links: Array.isArray(col.links)
              ? col.links
                  .filter((l): l is Record<string, unknown> => !!l && typeof l === "object")
                  .slice(0, 6)
                  .map((l) => ({ label: str(l.label, 40) ?? "", href: str(l.href, 500) ?? "#" }))
                  .filter((l) => l.label)
              : [],
          }))
          .filter((col) => col.title || col.links.length > 0)
      : [];
    const aparat =
      typeof f.socialAparat === "string" &&
      (f.socialAparat.startsWith("https://") || f.socialAparat.startsWith("/uploads/storefront/"))
        ? f.socialAparat.trim().slice(0, 400)
        : null;
    out.footer = {
      note: str(f.note, 300) ?? "",
      showMap: typeof f.showMap === "boolean" ? f.showMap : true,
      showSocials: typeof f.showSocials === "boolean" ? f.showSocials : true,
      aboutTitle: str(f.aboutTitle, 100) ?? "",
      aboutText: str(f.aboutText, 1200) ?? "",
      columns,
      copyright: str(f.copyright, 200) ?? "",
      socialAparat: aparat,
      showPoweredBy: typeof f.showPoweredBy === "boolean" ? f.showPoweredBy : true,
    };
  }
  if (Array.isArray(c.trustNotes)) {
    out.trustNotes = c.trustNotes
      .filter((n): n is string => typeof n === "string")
      .map((n) => n.trim().slice(0, 90))
      .filter(Boolean)
      .slice(0, 5);
  }
  if (c.sections && typeof c.sections === "object") {
    const s = c.sections as Record<string, unknown>;
    out.sections = {
      showCategories: typeof s.showCategories === "boolean" ? s.showCategories : true,
      showFeatures: typeof s.showFeatures === "boolean" ? s.showFeatures : true,
      showStats: typeof s.showStats === "boolean" ? s.showStats : true,
      showAbout: typeof s.showAbout === "boolean" ? s.showAbout : true,
      showTrustBar: typeof s.showTrustBar === "boolean" ? s.showTrustBar : true,
      showNewsletter: typeof s.showNewsletter === "boolean" ? s.showNewsletter : false,
      productsTitle: str(s.productsTitle, 80) ?? "",
    };
  }
  return out;
}

