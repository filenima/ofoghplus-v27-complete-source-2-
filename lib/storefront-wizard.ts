/** آوانویسی یک واژهٔ فارسی — «بهاران» → baharan؛ خروجی خالی یعنی ترجمه‌ناپذیر */
export function transliterateFaWord(word: string): string {
  return normalizeFaText(word)
    .split("")
    .map((ch) => FA_LETTER_MAP[ch] ?? "")
    .join("")
    .replace(/[^a-z]/g, "")
    .slice(0, 14);
}

/**
 * پیشنهاد اسلاگ/دامنهٔ کوتاه متناسب با برند:
 * ۱) ترجمهٔ واژه‌به‌واژهٔ نام فارسی → ترکیب ۲ واژهٔ کوتاه
 * ۲) ترکیب واژهٔ برند + واژهٔ صنعت
 * ۳) ترکیب واژهٔ صنعت + پسوند برند
 * خروجی همیشه کوتاه (۵-۱۴ نویسه)، لاتین، بدون کاراکتر ابهام
 */
export function suggestStoreSlugCandidates(businessName: string, businessTypeId: string): string[] {
  const type = getBusinessType(businessTypeId);
  const norm = normalizeFaText(businessName);
  const words = norm.split(" ").filter((w) => w && !STOP_WORDS.has(w));
  // ترجمهٔ واژه‌نامه‌ای؛ واژهٔ ناشناخته با آوانویسی حرف‌به‌حرف (بهاران → baharan)
  const translated = words
    .map((w) => FA_TO_EN_WORD[w] ?? transliterateFaWord(w))
    .filter(Boolean);

  const industry = type?.domainWords ?? ["shop"];
  const candidates: string[] = [];

  // ۱) ترکیب ترجمهٔ نام (اگر ترجمه‌پذیر بود)
  if (translated.length >= 1) {
    candidates.push(translated.slice(0, 2).join("-"));
    if (translated.length >= 2) candidates.push(translated.slice(0, 2).join(""));
  }
  // ۲) واژهٔ اول نام + صنعت
  if (translated[0]) {
    candidates.push(`${translated[0]}-${industry[0]}`);
    candidates.push(`${industry[0]}${translated[0]}`);
  }
  // ۳) صنعت + پسوند کوتاه
  candidates.push(`${industry[0]}-plus`);
  candidates.push(`${industry[0]}${industry[1] ?? "land"}`);
  candidates.push(`my-${industry[0]}`);
  candidates.push(`${industry[0]}1`);

  // پاک‌سازی + طول ۳-۱۸ + یکتا
  const seen = new Set<string>();
  const out: string[] = [];
  for (const c of candidates) {
    const s = c.toLowerCase().replace(/[^a-z0-9-]/g, "").replace(/-{2,}/g, "-").replace(/^-|-$/g, "");
    if (s.length >= 3 && s.length <= 18 && !seen.has(s)) {
      seen.add(s);
      out.push(s);
    }
  }
  return out.slice(0, 8);
}

/** دامنه‌های پیشنهادی روی برند-کاربر (ساب‌دامنهٔ رایگان پلتفرم) */
export const STOREFRONT_BASE_DOMAIN = "ofoghplus.ir";

export function suggestDomainCandidates(businessName: string, businessTypeId: string): string[] {
  const slugs = suggestStoreSlugCandidates(businessName, businessTypeId);
  return slugs.map((s) => `${s}.${STOREFRONT_BASE_DOMAIN}`);
}

