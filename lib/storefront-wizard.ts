/** حذف اعراب/نیم‌فاصله و نرمال‌سازی برای تحلیل نام */
export function normalizeFaText(input: string): string {
  return String(input || "")
    .replace(/[\u064B-\u065F\u0670\u0640]/g, "") // اعراب + کشیده
    .replace(/\u200C/g, " ") // نیم‌فاصله → فاصله
    .replace(/\s+/g, " ")
    .trim();
}

