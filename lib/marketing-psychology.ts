/** کمکی امن برای جایگزینی {n} و {app} در الگوهای بالا */
export function fillPsychoTemplate(
  template: string,
  vars: { n?: number | string; app?: string }
): string {
  let out = template;
  if (vars.n !== undefined) out = out.replaceAll("{n}", String(vars.n));
  if (vars.app !== undefined) out = out.replaceAll("{app}", vars.app);
  return out;
}

